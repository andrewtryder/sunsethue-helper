#!/usr/bin/env node
/**
 * Render wrangler.toml, wrangler.worker.toml, and wrangler.credential-admin.toml
 * from the committed *.example.toml templates.
 *
 * Usage:
 *   node scripts/generate-wrangler-config.mjs           # placeholders allowed
 *   node scripts/generate-wrangler-config.mjs --strict   # fail if required env missing
 */
import { readFile, writeFile } from "node:fs/promises";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { resolveTemplateValues } from "./lib/project-config.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");

const TEMPLATES = [
  {
    template: "wrangler.example.toml",
    output: "wrangler.toml",
    tokens: ["PAGES_PROJECT_NAME", "WORKER_NAME"]
  },
  {
    template: "wrangler.worker.example.toml",
    output: "wrangler.worker.toml",
    tokens: [
      "WORKER_NAME",
      "D1_DATABASE_NAME",
      "D1_DATABASE_ID",
      "CREDENTIAL_ADMIN_WORKER_NAME",
      "SECRETS_STORE_ID"
    ]
  },
  {
    template: "wrangler.credential-admin.example.toml",
    output: "wrangler.credential-admin.toml",
    tokens: [
      "CREDENTIAL_ADMIN_WORKER_NAME",
      "CLOUDFLARE_ACCOUNT_ID",
      "SECRETS_STORE_ID"
    ]
  }
];

const HEADER = `# Generated by scripts/generate-wrangler-config.mjs — do not edit or commit.
# Source templates: wrangler.example.toml, wrangler.worker.example.toml, wrangler.credential-admin.example.toml.
`;

/**
 * Replace {{TOKEN}} markers. Unknown leftover tokens are an error so a typo
 * cannot silently ship an unusable config.
 */
export function renderTemplate(source, values) {
  const remaining = new Set();
  const rendered = source.replace(/\{\{([A-Z0-9_]+)\}\}/g, (match, token) => {
    if (!(token in values) || values[token] === undefined || values[token] === null) {
      remaining.add(token);
      return match;
    }
    return String(values[token]);
  });
  if (remaining.size > 0) {
    throw new Error(
      `Unresolved Wrangler template token${remaining.size === 1 ? "" : "s"}: ${[...remaining].sort().join(", ")}`
    );
  }
  if (/\{\{[A-Z0-9_]+\}\}/.test(rendered)) {
    throw new Error("Unresolved Wrangler template tokens remain after render");
  }
  return rendered;
}

export async function generateWranglerConfig({
  strict = false,
  requireSecretsStore = false,
  root = ROOT
} = {}) {
  const values = resolveTemplateValues({
    strict,
    requireSecretsStore: strict || requireSecretsStore
  });
  values.WEB_PUSH_VARS = renderWebPushVars();
  const written = [];

  for (const entry of TEMPLATES) {
    const source = await readFile(resolve(root, entry.template), "utf8");
    const rendered = renderTemplate(source, values);
    const outputPath = resolve(root, entry.output);
    await writeFile(outputPath, `${HEADER}\n${rendered}`, "utf8");
    written.push(entry.output);
  }

  return {
    written,
    values: {
      ...values,
      D1_DATABASE_ID: "[redacted]",
      SECRETS_STORE_ID: values.SECRETS_STORE_ID ? "[redacted]" : values.SECRETS_STORE_ID,
      CLOUDFLARE_ACCOUNT_ID: values.CLOUDFLARE_ACCOUNT_ID ? "[redacted]" : values.CLOUDFLARE_ACCOUNT_ID,
      WEB_PUSH_VARS: values.WEB_PUSH_VARS ? "[redacted]" : values.WEB_PUSH_VARS
    }
  };
}

function renderWebPushVars() {
  const publicKey = (process.env.WEB_PUSH_VAPID_PUBLIC_KEY || "").trim();
  const subject = (process.env.WEB_PUSH_SUBJECT || "").trim();
  if (!publicKey && !subject) return "";
  if (!publicKey || !subject) {
    throw new Error("Both WEB_PUSH_VAPID_PUBLIC_KEY and WEB_PUSH_SUBJECT must be set together");
  }
  return [
    "[vars]",
    `WEB_PUSH_VAPID_PUBLIC_KEY = "${publicKey.replace(/"/g, "")}"`,
    `WEB_PUSH_SUBJECT = "${subject.replace(/"/g, "")}"`
  ].join("\n");
}

async function main() {
  const strict = process.argv.includes("--strict");
  const result = await generateWranglerConfig({ strict, requireSecretsStore: strict });
  console.log(
    JSON.stringify(
      {
        ok: true,
        written: result.written,
        workerName: result.values.WORKER_NAME,
        credentialAdminWorkerName: result.values.CREDENTIAL_ADMIN_WORKER_NAME,
        pagesProject: result.values.PAGES_PROJECT_NAME
      },
      null,
      2
    )
  );
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1]);
if (isMain) {
  main().catch((error) => {
    console.error(error instanceof Error ? error.message : "config generation failed");
    process.exitCode = 1;
  });
}
